"""REST for the compatibility registry (Milestone 5, workstream F): ``GET /api/v1/compatibility``.

Read-only. Serves ``compat/registry.json`` (generated by ``make compat``; levels derived from
evidence, docs/COMPATIBILITY.md) and attaches what this installation has: built-in adapters
importable or not, installed plugins and their versions from the last plugin discovery.
Live status never changes a level.
"""

from __future__ import annotations

import asyncio
import logging
from typing import Annotated

from fastapi import APIRouter, Depends
from pydantic import BaseModel, Field

from concord import __version__
from concord.compat.live import InstalledPlugin, LiveStatus, live_status, load_registry
from concord.compat.model import Registry
from concord.runtime.plugins import PluginRecord, PluginRegistry
from concord.server.deps import AppServices, services

log = logging.getLogger(__name__)
router = APIRouter(prefix="/api/v1")
Svc = Annotated[AppServices, Depends(services)]


class PluginDiscoveryInfo(BaseModel):
    discovering: bool
    discovered_at_ns: int | None
    error: str | None


class CompatibilityResponse(BaseModel):
    available: bool = Field(description="False: the registry file is missing or invalid")
    source: str
    error: str | None = None
    concord_version: str
    registry: Registry | None = None
    live: dict[str, LiveStatus] = Field(
        default_factory=dict, description="per entry id: what this installation has"
    )
    plugin_discovery: PluginDiscoveryInfo


def _installed(r: PluginRecord) -> InstalledPlugin:
    dist = r.dist or {}
    return InstalledPlugin(
        package=dist.get("name") or (r.manifest.name if r.manifest else r.name),
        version=dist.get("version") or (r.manifest.version if r.manifest else None),
        status=r.status,
        reason=r.reason,
    )


def _discovery(reg: PluginRegistry) -> PluginDiscoveryInfo:
    st = reg.status()
    return PluginDiscoveryInfo(
        discovering=bool(st["discovering"]),
        discovered_at_ns=st["discovered_at_ns"],
        error=st["error"],
    )


@router.get("/compatibility")
async def compatibility(svc: Svc) -> CompatibilityResponse:
    """The compatibility registry plus this installation's live status per entry."""
    path = svc.settings.compat_registry
    plugins = svc.runtime.registry.plugins
    discovery = _discovery(plugins)
    try:
        registry = await asyncio.to_thread(load_registry, path)
    except (OSError, ValueError) as exc:
        message = f"compatibility registry unavailable ({path.name}): {exc}"[:500]
        log.warning("%s", message)
        svc.runtime.diagnostics.record_error("compatibility_registry", None, message)
        return CompatibilityResponse(
            available=False,
            source=path.name,
            error=message,
            concord_version=__version__,
            plugin_discovery=discovery,
        )
    installed = (
        [_installed(r) for r in plugins.records()]
        if discovery.discovered_at_ns is not None
        else None
    )
    live = live_status(registry, concord_version=__version__, installed_plugins=installed)
    return CompatibilityResponse(
        available=True,
        source=path.name,
        concord_version=__version__,
        registry=registry,
        live=dict(live),
        plugin_discovery=discovery,
    )
