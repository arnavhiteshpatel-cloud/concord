"""Server settings: environment variables > config file (brainos.config) > safe defaults.

No secrets are configured anywhere; the config file is validated and refused if other users
can modify it. See docs/SECURITY.md and ``brainos config init``.
"""

from __future__ import annotations

import os
from dataclasses import dataclass, field
from pathlib import Path

from brainos.config import (
    FileConfig,
    Retention,
    coerce_env,
    default_data_dir,
    default_reports_dir,
    default_static_dir,
    load_config,
)
from brainos.runtime.recorder import (
    MAX_BYTES,
    MAX_DURATION_NO_RAW_S,
    MAX_DURATION_S,
    MIN_FREE_BYTES,
)

MIB = 1024 * 1024

REPO_ROOT = Path(__file__).resolve().parents[4]
COMPAT_REGISTRY = REPO_ROOT / "compat" / "registry.json"  # M5-F, generated by `make compat`


def _flag(name: str, default: bool) -> bool:
    raw = os.environ.get(name)
    if raw is None:
        return default
    return raw.strip().lower() in {"1", "true", "yes", "on"}


@dataclass(frozen=True)
class Settings:
    host: str = "127.0.0.1"
    port: int = 8000
    data_dir: Path = REPO_ROOT / "data"
    reports_dir: Path = REPO_ROOT / "reports"
    static_dir: Path | None = REPO_ROOT / "frontend" / "dist"
    enable_sim: bool = True
    log_level: str = "INFO"
    queue_size: int = 2048
    reconnect_backoff_s: tuple[float, ...] = field(default=(0.2, 0.5, 1.0))
    seed: int | None = None
    # Source plugins (adapter SDK): discovered at startup unless disabled; hosts run with
    # plugin_python (default: this interpreter) and plugin_path prepended to PYTHONPATH.
    discover_plugins: bool = True
    plugin_python: str | None = None
    plugin_path: tuple[str, ...] = field(default=())
    # Compatibility registry (M5-F), generated by `make compat`; served read-only.
    compat_registry: Path = COMPAT_REGISTRY
    # Milestone 5 (D): installation, security, retention
    allow_remote: bool = False  # a non-loopback host is refused without it
    open_browser: bool = True
    retention: Retention = field(default_factory=Retention)
    config_path: Path | None = None  # the config file that was read (None: none exists)
    # Recording limits ([recording] in the config file; BRAINOS_RECORDING_*)
    recording_max_duration_s: float = MAX_DURATION_S
    recording_max_duration_no_raw_s: float = MAX_DURATION_NO_RAW_S
    recording_max_bytes: int = MAX_BYTES
    recording_min_free_bytes: int = MIN_FREE_BYTES

    @property
    def recordings_dir(self) -> Path:
        return self.data_dir / "recordings"

    @property
    def datasets_dir(self) -> Path:
        return self.data_dir / "datasets"

    @property
    def models_dir(self) -> Path:
        return self.data_dir / "models"

    @property
    def sessions_dir(self) -> Path:
        return self.data_dir / "sessions"

    @property
    def logs_dir(self) -> Path:
        return self.data_dir / "logs"

    @property
    def log_file(self) -> Path:
        return self.logs_dir / "brainos.log"

    @property
    def pid_file(self) -> Path:
        return self.data_dir / "brainos.pid"

    @property
    def url(self) -> str:
        host = "127.0.0.1" if self.host in ("0.0.0.0", "::") else self.host
        host = f"[{host}]" if ":" in host else host
        return f"http://{host}:{self.port}"

    @classmethod
    def from_env(cls, config: FileConfig | None = None) -> Settings:
        """Effective settings. Raises ``brainos.config.ConfigError`` for an unusable file."""
        cfg = config if config is not None else load_config()

        def pick(env: str, section: str, key: str, default: object) -> object:
            raw = os.environ.get(env)
            if raw is not None:
                return raw
            value = cfg.get(section, key)
            return default if value is None else value

        def flag(env: str, section: str, key: str, default: bool) -> bool:
            value = cfg.get(section, key)
            return _flag(env, default if value is None else bool(value))

        def number(env: str, key: str, default: float) -> float:
            raw = os.environ.get(env)
            if raw is not None:
                return float(coerce_env(env, "recording", key, raw))
            value = cfg.get("recording", key)
            return default if value is None else float(value)

        static = os.environ.get("BRAINOS_STATIC_DIR")
        data_dir = Path(str(pick("BRAINOS_DATA_DIR", "storage", "data_dir", default_data_dir())))
        reports = pick("BRAINOS_REPORTS_DIR", "storage", "reports_dir", default_reports_dir())
        return cls(
            host=str(pick("BRAINOS_HOST", "server", "host", cls.host)),
            port=int(str(pick("BRAINOS_PORT", "server", "port", cls.port))),
            data_dir=data_dir.expanduser(),
            reports_dir=Path(str(reports)).expanduser(),
            static_dir=Path(static) if static else default_static_dir(),
            enable_sim=flag("BRAINOS_ENABLE_SIM", "simulation", "enabled", True),
            log_level=str(pick("BRAINOS_LOG_LEVEL", "server", "log_level", "INFO")).upper(),
            discover_plugins=flag("BRAINOS_PLUGINS", "plugins", "discover", True),
            plugin_python=os.environ.get("BRAINOS_PLUGIN_PYTHON") or None,
            plugin_path=tuple(
                p for p in os.environ.get("BRAINOS_PLUGIN_PATH", "").split(os.pathsep) if p
            ),
            compat_registry=Path(os.environ.get("BRAINOS_COMPAT_REGISTRY", str(COMPAT_REGISTRY))),
            allow_remote=flag("BRAINOS_ALLOW_REMOTE", "server", "allow_remote", False),
            open_browser=flag("BRAINOS_OPEN_BROWSER", "server", "open_browser", True),
            retention=cfg.retention(),
            config_path=cfg.path if cfg.exists else None,
            recording_max_duration_s=number(
                "BRAINOS_RECORDING_MAX_S", "max_duration_s", MAX_DURATION_S
            ),
            recording_max_duration_no_raw_s=number(
                "BRAINOS_RECORDING_MAX_NO_RAW_S", "max_duration_no_raw_s", MAX_DURATION_NO_RAW_S
            ),
            recording_max_bytes=int(
                number("BRAINOS_RECORDING_MAX_MB", "max_size_mb", MAX_BYTES / MIB) * MIB
            ),
            recording_min_free_bytes=int(
                number("BRAINOS_RECORDING_MIN_FREE_MB", "min_free_mb", MIN_FREE_BYTES / MIB) * MIB
            ),
        )
