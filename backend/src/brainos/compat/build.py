class Repo:
    """Read-only view of a checkout. Paths are relative and never leave the root."""

    def __init__(self, root: Path) -> None:
        self.root = root.resolve()

    def path(self, rel: str) -> Path:
        p = (self.root / rel).resolve()
        if p != self.root and self.root not in p.parents:
            raise CompatError(f"path {rel!r} leaves the repository")
        return p

    def exists(self, rel: str) -> bool:
        return self.path(rel).exists()

    def text(self, rel: str, where: str) -> str:
        p = self.path(rel)
        if not p.is_file():
            raise CompatError(f"{where}: {rel} does not exist")
        try:
            return p.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError) as exc:
            raise CompatError(f"{where}: cannot read {rel}: {exc}") from None

    def code_text(self, rel: str, where: str) -> str:
        """A module file, or every .py file of a package directory."""
        p = self.path(rel)
        if p.is_dir():
            return "\n".join(
                f.read_text(encoding="utf-8")
                for f in sorted(p.rglob("*.py"))
                if "__pycache__" not in f.parts
            )
        return self.text(rel, where)


# ------------------------------------------------------------------------------ helpers


def _check_date(value: str, where: str) -> None:
    try:
        day = dt.date.fromisoformat(value)
    except ValueError:
        raise CompatError(f"{where}: date {value!r} is not an ISO date") from None
    if day > dt.datetime.now(dt.UTC).date() + dt.timedelta(days=1):
        raise CompatError(f"{where}: date {value} is in the future")


def _pyproject(repo: Repo, source_dir: str, where: str) -> dict[str, Any]:
    try:
        doc = tomllib.loads(repo.text(f"{source_dir}/pyproject.toml", where))
    except tomllib.TOMLDecodeError as exc:
        raise CompatError(f"{where}: {source_dir}/pyproject.toml: {exc}") from None
    project = doc.get("project")
    if not isinstance(project, dict):
        raise CompatError(f"{where}: {source_dir}/pyproject.toml has no [project] table")
    return project


def tree_sha256(package_dir: Path) -> tuple[str, dict[str, str]]:
    """The same file-tree hash brainos-certify records (``identity.module.tree_sha256``)."""
    paths: list[str] = []
    for dirpath, dirnames, filenames in os.walk(package_dir):
        dirnames[:] = sorted(x for x in dirnames if x != "__pycache__")
        paths += [
            os.path.join(dirpath, fn)
            for fn in sorted(filenames)
            if not fn.endswith((".pyc", ".pyo"))
        ]
    tree = hashlib.sha256()
    files: dict[str, str] = {}
    for p in sorted(paths)[:MAX_TREE_FILES]:
        rel = os.path.relpath(p, package_dir).replace(os.sep, "/")
        digest = hashlib.sha256(Path(p).read_bytes()).hexdigest()
        files[rel] = digest
        tree.update(f"{rel}\0{digest}\n".encode())
    return tree.hexdigest(), files


def _certify_schema_errors(doc: Mapping[str, Any]) -> list[str]:
    """Violations of brainos-certify's own report schema (when brainos-certify is installed)."""
    try:
        schema_file = resources.files("brainos_certify").joinpath("schemas/report.schema.json")
        schema = json.loads(schema_file.read_text(encoding="utf-8"))
    except (ModuleNotFoundError, OSError, ValueError) as exc:
        log.info("brainos-certify report schema not available (%s): consistency checked only", exc)
        return []
    return validate_against_schema(doc, schema)


def _get(doc: Any, *keys: str) -> Any:
    for k in keys:
        if not isinstance(doc, Mapping):
            return None
        doc = doc.get(k)
    return doc


# ------------------------------------------------------------------------------ evidence


def curated_evidence(repo: Repo, item: SourceEvidence, where: str) -> Evidence:
    """Verify one curated item against the checkout and classify it (R1, R2, R5, R7)."""
    where = f"{where} evidence {item.path}"
    check_source_item(item, where)
    _check_date(item.date, where)
    if not repo.path(item.path).is_file():
        raise CompatError(f"{where}: evidence path does not exist")
    if item.anchor is not None and item.anchor not in repo.text(item.path, where):
        raise CompatError(f"{where}: anchor {item.anchor!r} not found in the file")
    supports = None
    note = None
    real = False
    if item.type == "test":
        if not TEST_FILE.search(item.path):
            raise CompatError(f"{where}: not a test file (tests/…, test_*.py, *.test.ts)")
        supports = support_of_test(item)
        if item.record is not None:
            text = repo.text(item.record.path, f"{where} record")
            if item.record.anchor not in text:
                raise CompatError(
                    f"{where}: recorded execution {item.record.anchor!r} not found in "
                    f"{item.record.path}"
                )
            note = f"Opt-in test, not run in CI; its execution is recorded in {item.record.path}"
        if item.dataset_manifest is not None:
            text = repo.text(item.dataset_manifest, f"{where} dataset_manifest")
            try:
                json.loads(text)
            except ValueError as exc:
                raise CompatError(f"{where}: {item.dataset_manifest} is not JSON: {exc}") from None
            if not SHA256.search(text):
                raise CompatError(f"{where}: {item.dataset_manifest} pins no SHA-256 checksums")
            real = True
    return Evidence(
        type=item.type,
        path=item.path,
        description=item.description,
        date=item.date,
        supports=supports,
        counted=True,
        note=note,
        protocol_reference=item.protocol_reference,
        runs_in_ci=item.runs_in_ci,
        record=item.record.path if item.record else None,
        real_data=real,
        claim=item.claim,
    )


@dataclass(frozen=True)
class Report:
    path: str
    doc: Mapping[str, Any]

    @property
    def package(self) -> str:
        return str(_get(self.doc, "plugin", "manifest", "name") or "")

    @property
    def version(self) -> str:
        return str(_get(self.doc, "plugin", "manifest", "version") or "")

    @property
    def generated_at(self) -> str:
        return str(self.doc.get("generated_at") or "")


def load_reports(repo: Repo) -> list[Report]:
    out: list[Report] = []
    base = repo.path(REPORTS_DIR)
    for p in sorted(base.glob("*.certify.json")) if base.is_dir() else []:
        rel = p.relative_to(repo.root).as_posix()
        try:
            doc = json.loads(p.read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            raise CompatError(f"{rel}: not a readable JSON report: {exc}") from None
        if not isinstance(doc, dict):
            raise CompatError(f"{rel}: not a JSON object")
        errors = _certify_schema_errors(doc)
        if errors:
            raise CompatError(
                f"{rel}: does not match the brainos-certify report schema: {errors[0]}"
            )
        problems = certify_problems(doc)
        if problems:
            raise CompatError(f"{rel}: refused, inconsistent certify report: {'; '.join(problems)}")
        report = Report(rel, doc)
        if not report.package or not report.version:
            raise CompatError(f"{rel}: report names no plugin package / version")
        dist = _get(doc, "plugin", "identity", "distribution", "name")
        if dist is not None and dist != report.package:
            raise CompatError(
                f"{rel}: manifest name {report.package!r} differs from distribution {dist!r}"
            )
        _check_date(report.generated_at[:10], rel)
        out.append(report)
    return out


@dataclass(frozen=True)
class Checkout:
    """A plugin package as it is in this repository."""

    version: str
    entry_point: str
    module: str
    tree: str
    files: dict[str, str]


def plugin_checkout(repo: Repo, supp: SourcePlugin) -> Checkout | None:
    if supp.source_dir is None:
        return None
    where = f"plugin {supp.package}"
    project = _pyproject(repo, supp.source_dir, where)
    if project.get("name") != supp.package:
        raise CompatError(f"{where}: {supp.source_dir} is the package {project.get('name')!r}")
    eps = _get(project, "entry-points", "brainos.sources")
    if not isinstance(eps, dict) or len(eps) != 1:
        raise CompatError(f"{where}: expected exactly one 'brainos.sources' entry point")
    ((name, value),) = eps.items()
    module = str(value).split(":", 1)[0].split(".", 1)[0]
    pkg_dir = next(
        (
            repo.path(d)
            for d in (f"{supp.source_dir}/src/{module}", f"{supp.source_dir}/{module}")
            if repo.path(d).is_dir()
        ),
        None,
    )
    if pkg_dir is None:
        raise CompatError(f"{where}: package directory for module {module!r} not found")
    tree, files = tree_sha256(pkg_dir)
    return Checkout(str(project.get("version")), str(name), module, tree, files)


def _data_source(doc: Mapping[str, Any]) -> str:
    origin = str(_get(doc, "plugin", "session", "origin") or "unknown origin")
    flags = [
        word
        for word, key in (("synthetic", "synthetic"), ("prerecorded", "prerecorded"))
        if _get(doc, "plugin", "session", key) is True
    ]
    return f"{origin} (declared {' + '.join(flags)})" if flags else origin


def certify_evidence(report: Report, checkout: Checkout | None) -> Evidence:
    """R1 / R2 / R5 for one certification report."""
    doc = report.doc
    achieved = certify_achieved(doc)
    highest = _get(doc, "levels", "highest")
    module = _get(doc, "plugin", "identity", "module")
    rep_tree = str(_get(module, "tree_sha256") or "")
    rep_files = {
        str(f.get("path")): str(f.get("sha256"))
        for f in (_get(module, "files") or [])
        if isinstance(f, Mapping)
    }
    counted = True
    note: str | None = None
    matches: bool | None = None
    changed: list[str] = []
    if checkout is None:
        note = (
            f"Plugin source not in this repository: the report applies to version "
            f"{report.version} as installed where it ran"
        )
    elif report.version != checkout.version:
        counted = False
        note = (
            f"Evidence for a different version: the report is for {report.version}, this "
            f"checkout has {checkout.version}"
        )
    else:
        matches = rep_tree == checkout.tree
        if not matches:
            changed = sorted(
                p
                for p in set(rep_files) | set(checkout.files)
                if rep_files.get(p) != checkout.files.get(p)
            )
            counted = False
            note = (
                "Evidence for an earlier revision of this version: plugin source changed after "
                f"this run ({', '.join(changed) or 'file set differs'}); re-run brainos-certify "
                "to count it"
            )
    counts = {str(k): int(v) for k, v in (_get(doc, "summary", "counts") or {}).items()}
    tool = f"brainos-certify {_get(doc, 'tool', 'version')}"
    elapsed = _get(doc, "options", "run", "duration_s")
    ref = _get(doc, "protocol_reference", "statement")
    att = _get(doc, "attestation", "accepted")
    device = _get(doc, "plugin", "device_key")
    level_text = str(highest or "no level")
    if highest == "protocol_tested" and ref:
        level_text = f"protocol_tested against {ref!r} (operator statement)"
    description = (
        f"{tool}"
        + (f", {elapsed:g} s run" if isinstance(elapsed, int | float) else "")
        + f" of {report.package} {report.version}"
        + (f" (device {device})" if device else "")
        + f": {counts.get('pass', 0)} pass, {counts.get('warn', 0)} warn, "
        f"{counts.get('fail', 0)} fail; {level_text}"
    )
    certify = CertifyInfo(
        level=highest
        if highest in ("adapter_implementation", "protocol_tested", "hardware_tested")
        else None,
        tool=tool,
        plugin=report.package,
        plugin_version=report.version,
        entry_point=str(_get(doc, "plugin", "entry_point") or ""),
        device_key=str(device) if device else None,
        data_source=_data_source(doc),
        counts=counts,
        protocol_reference=str(ref) if ref else None,
        attestation_accepted=att if isinstance(att, bool) else None,
        tree_sha256=rep_tree,
        source_matches=matches,
        changed_files=changed,
    )
    return Evidence(
        type="certify_report",
        path=report.path,
        description=description,
        date=report.generated_at[:10],
        supports=certify_support(achieved),
        counted=counted,
        note=note,
        certify=certify,
    )


# ------------------------------------------------------------------------------ entries


def _entry(
    *,
    base: dict[str, Any],
    evidence: list[Evidence],
) -> Entry:
    level, real, basis = derive_level(evidence)
    return Entry(
        **base,
        level=level,
        level_number=level_number(level),
        real_data_replay=real,
        level_basis=basis,
        evidence=evidence,
    )


def _read_only(repo: Repo, ro: ReadOnly, where: str) -> ReadOnly:
    for p in ro.verified_by:
        if not repo.path(p).is_file():
            raise CompatError(f"{where}: read_only.verified_by {p} does not exist")
    return ro


def _module_of(code: str) -> str | None:
    """``backend/src/brainos/adapters/lsl`` -> ``brainos.adapters.lsl``."""
    prefix = "backend/src/"
    if not code.startswith(prefix):
        return None
    return code[len(prefix) :].removesuffix(".py").replace("/", ".")


def builtin_entry(repo: Repo, b: SourceBuiltin, brainos_version: str) -> Entry:
    where = f"builtin {b.id}"
    base: dict[str, Any] = {
        "id": b.id,
        "display_name": b.display_name,
        "kind": b.kind,
        "ecosystem": b.ecosystem,
        "protocol": b.protocol,
        "package": "brainos",
        "version": brainos_version,
        "adapter": b.id,
        "entry_point": None,
        "module": _module_of(b.code),
        "synthetic_only": b.synthetic_only,
        "modalities_declared": list(b.modalities_declared),
        "modality_note": b.modality_note,
        "not_tested": list(b.not_tested),
        "limitations": list(b.limitations),
        "requires_modules": list(b.requires_modules),
    }
    if not repo.exists(b.code):
        log.info("%s: %s not in this checkout; listed without evidence", where, b.code)
        return Entry(
            **base,
            in_checkout=False,
            read_only=b.read_only,
            level=None,
            level_number=None,
            real_data_replay=False,
            level_basis=[f"not in this checkout: {b.code} does not exist; evidence not read"],
            evidence=[],
        )
    code = repo.code_text(b.code, where)
    if not re.search(rf"[\"']{re.escape(b.id)}[\"'@]", code):
        raise CompatError(f"{where}: the adapter name {b.id!r} does not appear in {b.code}")
    for m in b.modalities_declared:
        if f"Modality.{m.upper()}" not in code:
            raise CompatError(f"{where}: declares modality {m!r} but {b.code} never uses it")
    evidence = [curated_evidence(repo, e, where) for e in b.evidence]
    return _entry(
        base={**base, "in_checkout": True, "read_only": _read_only(repo, b.read_only, where)},
        evidence=evidence,
    )


def _modalities(reports: Sequence[Report]) -> tuple[list[str], str | None]:
    found: set[str] = set()
    for r in reports:
        for s in _get(r.doc, "plugin", "session", "streams") or []:
            if isinstance(s, Mapping) and s.get("modality"):
                found.add(str(s["modality"]))
    if not reports:
        return [], "no certified session: modality unknown"
    newest = max(reports, key=lambda r: r.generated_at)
    parts = [
        f"{s.get('stream_id')} ({s.get('role')}): {s.get('modality') or 'not declared'}"
        for s in _get(newest.doc, "plugin", "session", "streams") or []
        if isinstance(s, Mapping)
    ]
    return sorted(found), "Declared in the certified session: " + "; ".join(parts)


def plugin_entry(
    repo: Repo, package: str, supp: SourcePlugin | None, reports: Sequence[Report]
) -> Entry:
    where = f"plugin {package}"
    checkout = plugin_checkout(repo, supp) if supp is not None else None
    evidence = [certify_evidence(r, checkout) for r in reports]
    if supp is not None:
        evidence += [curated_evidence(repo, e, where) for e in supp.evidence]
    newest = max(reports, key=lambda r: r.generated_at) if reports else None
    manifest = _get(newest.doc, "plugin", "manifest") if newest else None
    if checkout is None and newest is None:
        raise CompatError(f"{where}: neither a source_dir nor a certify report identifies it")
    version = checkout.version if checkout else newest.version if newest else ""
    entry_point = (
        checkout.entry_point
        if checkout
        else str(_get(newest.doc, "plugin", "entry_point") or "")
        if newest
        else ""
    )
    counted_reports = [r for r, e in zip(reports, evidence, strict=False) if e.counted]
    modalities, modality_note = _modalities(counted_reports or list(reports))
    if supp is not None:
        not_tested, limitations = list(supp.not_tested), list(supp.limitations)
        read_only = _read_only(repo, supp.read_only, where)
        protocol = supp.protocol
    else:  # a report without curated additions: what the report itself says is missing
        missing = _get(newest.doc, "levels", "levels") if newest else None
        not_tested = [
            f"{name}: {m}"
            for name in ("protocol_tested", "hardware_tested")
            if isinstance(missing, Mapping) and not _get(missing, name, "achieved")
            for m in (_get(missing, name, "missing") or [])[:2]
        ]
        limitations = []
        read_only = _read_only(repo, DEFAULT_PLUGIN_READ_ONLY, where)
        protocol = "adapter SDK source plugin"
    display = (supp.display_name if supp else None) or _get(manifest, "display_name") or package
    return _entry(
        base={
            "id": package,
            "display_name": str(display),
            "kind": "source_plugin",
            "ecosystem": _get(manifest, "ecosystem"),
            "protocol": protocol,
            "package": package,
            "version": version,
            "adapter": None,
            "entry_point": entry_point or None,
            "module": checkout.module if checkout else None,
            "in_checkout": checkout is not None,
            "synthetic_only": False,
            "modalities_declared": modalities,
            "modality_note": modality_note,
            "read_only": read_only,
            "not_tested": not_tested,
            "limitations": limitations,
            "requires_modules": [],
        },
        evidence=evidence,
    )


# ------------------------------------------------------------------------------ build


def load_sources(repo: Repo) -> Sources:
    text = repo.text(SOURCES, "sources")
    try:
        return Sources.model_validate_json(text)
    except ValidationError as exc:
        first = exc.errors()[0]
        loc = ".".join(str(x) for x in first["loc"])
        hint = (
            " (levels are derived from evidence, never typed in)"
            if str(first["loc"][-1]) in ("level", "levels", "level_number")
            else ""
        )
        raise CompatError(f"{SOURCES}: {loc}: {first['msg']}{hint}") from None


def _brainos_version(repo: Repo) -> str:
    return str(_pyproject(repo, "backend", "brainos").get("version"))


def _check_level_names(repo: Repo) -> None:
    text = repo.text(VALIDATION_LEVELS, "levels")
    for d in LEVEL_DEFINITIONS:
        if f"**{d.number}. {d.name}**" not in text:
            raise CompatError(f"{VALIDATION_LEVELS} no longer defines '{d.number}. {d.name}'")


def build_registry(repo: Repo) -> Registry:
    sources = load_sources(repo)
    _check_level_names(repo)
    version = _brainos_version(repo)
    ids = [b.id for b in sources.builtins] + [p.package for p in sources.plugins]
    dupes = sorted({i for i in ids if ids.count(i) > 1})
    if dupes:
        raise CompatError(f"{SOURCES}: duplicate ids {dupes}")
    entries = [builtin_entry(repo, b, version) for b in sources.builtins]
    reports = load_reports(repo)
    supps = {p.package: p for p in sources.plugins}
    packages = list(supps) + sorted({r.package for r in reports} - set(supps))
    for pkg in packages:
        mine = [r for r in reports if r.package == pkg]
        entries.append(plugin_entry(repo, pkg, supps.get(pkg), mine))
    summary: dict[str, int] = {
        d.id: sum(e.level == d.id for e in entries) for d in LEVEL_DEFINITIONS
    }
    summary["no_level"] = sum(e.level is None for e in entries)
    top = summary["hardware_verified"] + summary["human_validated"]
    notice = (
        "Levels are derived from the evidence listed for each entry by rules R1-R7; none is "
        "entered by hand. An entry is at the highest level whose evidence exists in this "
        "checkout, not the level it was designed for. "
        + (
            "No entry has reached hardware_verified (level 3) or human_validated (level 4)."
            if top == 0
            else f"{top} entr{'y has' if top == 1 else 'ies have'} reached level 3 or 4."
        )
    )
    return Registry(
        registry_version=REGISTRY_VERSION,
        notice=notice,
        brainos_version=version,
        levels=list(LEVEL_DEFINITIONS),
        rules=list(RULES),
        sources=RegistrySources(
            curated=SOURCES,
            certify_reports=[r.path for r in reports],
            validation_levels=VALIDATION_LEVELS,
        ),
        summary=summary,
        entries=entries,
    )


def registry_schema() -> dict[str, Any]:
    schema = Registry.model_json_schema()
    schema.pop("title", None)
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "https://brainos.local/schemas/compat-registry.v1.json",
        "title": f"BrainOS compatibility registry {REGISTRY_VERSION}",
        **schema,
    }


def _json(doc: Any) -> str:
    return json.dumps(doc, indent=2, ensure_ascii=False) + "\n"


def validate_against_schema(data: Any, schema: Mapping[str, Any]) -> list[str]:
    try:
        import jsonschema
    except ImportError:
        log.info("jsonschema not installed: registry validated by its pydantic models only")
        return []
    v = jsonschema.Draft202012Validator(schema)
    return [
        f"{'/'.join(str(p) for p in e.absolute_path) or '(root)'}: {e.message[:200]}"
        for e in v.iter_errors(data)
    ]


# ------------------------------------------------------------------------------ markdown


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _link(path: str) -> str:
    return f"[{path.rsplit('/', 1)[-1]}](../{path})"


def level_words(e: Entry) -> str:
    if e.level is None:
        return "none (not in this checkout)" if not e.in_checkout else "none (no counted evidence)"
    d = next(d for d in LEVEL_DEFINITIONS if d.id == e.level)
    return f"{d.number}: {d.name}" + (" · real-data replay" if e.real_data_replay else "")


def render_markdown(reg: Registry) -> str:
    lines = [
        BEGIN,
        "",
        f"_Generated from `{REGISTRY}` (registry {reg.registry_version}, BrainOS "
        f"{reg.brainos_version}) by `make compat`; CI fails when it is stale "
        "(`python -m brainos.compat.build --check`). Edit `compat/sources.json` or add certify "
        "reports, never this table._",
        "",
        reg.notice,
        "",
        "| Integration | Kind | Package | Level (derived) | Counted evidence | Not tested |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for e in reg.entries:
        counted = [x for x in e.evidence if x.counted and (x.supports or x.claim)]
        lines.append(
            "| "
            + " | ".join(
                _cell(c)
                for c in (
                    f"{e.display_name} (`{e.id}`)",
                    KIND_WORDS[e.kind],
                    f"{e.package} {e.version}",
                    level_words(e),
                    ", ".join(_link(x.path) for x in counted) or "—",
                    " ".join(e.not_tested) or "—",
                )
            )
            + " |"
        )
    excluded = [(e, x) for e in reg.entries for x in e.evidence if not x.counted]
    if excluded:
        lines += ["", "Evidence listed but **not counted**:", ""]
        lines += [f"- `{e.id}`: {_link(x.path)}: {x.note}" for e, x in excluded]
    lines += ["", "Derivation rules:", ""]
    lines += [f"- {r}" for r in reg.rules]
    lines += ["", END]
    return "\n".join(lines)


def splice(doc: str, section: str) -> str:
    start, end = doc.find(BEGIN), doc.find(END)
    if start < 0 or end < start:
        raise CompatError(f"{DOC}: registry markers not found ({BEGIN!r} … {END!r})")
    return doc[:start] + section + doc[end + len(END) :]


def build(root: Path = REPO_ROOT) -> Outputs:
    repo = Repo(root)
    reg = build_registry(repo)
    data = reg.model_dump(mode="json")
    schema = registry_schema()
    problems = validate_against_schema(data, schema)
    if problems:
        raise CompatError(f"generated registry does not match its schema: {problems[0]}")
    Registry.model_validate(data)  # round trip
    doc = splice(repo.text(DOC, "docs"), render_markdown(reg))
    return Outputs(reg, {REGISTRY: _json(data), SCHEMA: _json(schema), DOC: doc})


def stale(root: Path, outputs: Outputs) -> list[str]:
    repo = Repo(root)
    out = []
    for rel, text in outputs.files.items():
        p = repo.path(rel)
        if not p.is_file() or p.read_text(encoding="utf-8") != text:
            out.append(rel)
    return out


def main(argv: Sequence[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m brainos.compat.build", description=__doc__)
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed files are stale")
    ap.add_argument("--root", type=Path, default=REPO_ROOT, help="repository root")
    args = ap.parse_args(argv)
    logging.basicConfig(level=logging.WARNING, format="%(levelname)s %(name)s: %(message)s")
    try:
        outputs = build(args.root)
    except CompatError as exc:
        print(f"compatibility registry refused: {exc}", file=sys.stderr)
        return 2
    if args.check:
        old = stale(args.root, outputs)
        if old:
            print(
                f"stale: {', '.join(old)}; run `make compat` (python -m brainos.compat.build) "
                "and commit the result",
                file=sys.stderr,
            )
            return 1
        print(f"compatibility registry is current ({len(outputs.registry.entries)} entries)")
        return 0
    repo = Repo(args.root)
    for rel, text in outputs.files.items():
        repo.path(rel).write_text(text, encoding="utf-8")
    s = outputs.registry.summary
    print(
        f"wrote {', '.join(outputs.files)}: {len(outputs.registry.entries)} entries; "
        + ", ".join(f"{k} {v}" for k, v in s.items())
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
