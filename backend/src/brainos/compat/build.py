"""Build the compatibility registry from integration metadata and evidence.

    python -m brainos.compat.build            # write compat/registry.json, its schema, and the
                                              # generated section of docs/COMPATIBILITY.md
    python -m brainos.compat.build --check    # exit 1 if any of them is stale (CI)

Inputs: ``compat/sources.json`` (curated: integrations and their evidence paths, never a
level) and every ``docs/compatibility/*.certify.json`` (brainos-certify reports). Every
evidence path must exist and every anchor must be found; certify reports are checked against
the brainos-certify report schema (when installed) and for internal consistency; plugin
versions and source hashes are compared with this checkout. Levels are derived by
:mod:`brainos.compat.rules`. Exit codes: 0 written / current, 1 stale (``--check``), 2 refused.
"""

