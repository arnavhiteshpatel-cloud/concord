// Reports & exports: trigger POST /studies/{sid}/exports, show the manifest and SHA-256 of every
// file, and re-verify each file's hash in the browser. The server keeps no copy of the export.
import { api } from '../api.js';
import { h, card, table, tile, fmtNum, fmtDateTime, shortHash, announce, clear, errorNotice, busy, notice, nextId } from '../ui.js';
import { readZip, sha256Hex, decodeText, webCryptoAvailable } from '../zip.js';

const REPORT_TYPES = [
  ['functional_assessment', 'Functional assessment report'],
  ['device_comparison', 'Device / modality comparison report'],
  ['psychometric_validation', 'Psychometric validation report'],
  ['home_use_feasibility', 'Home-use feasibility report'],
  ['sponsor_study_summary', 'Sponsor study summary'],
  ['evidence_package', 'Clinical research evidence package'],
  ['payer_evidence_planning', 'Payer-oriented evidence planning report'],
];

const history = []; // exports generated in this browser tab (metadata only; data stays in memory)

export async function exportsView(root, ctx) {
  root.appendChild(h('div', { class: 'page-head' }, h('h1', null, 'Reports & data exports')));
  const audiences = [];
  if (ctx.can('export.sponsor')) audiences.push({ value: 'sponsor', label: 'Sponsor package (pseudonymous, sponsor-shareable participants only)' });
  if (ctx.can('export.full')) audiences.push({ value: 'full', label: 'Full site package (all participants at your sites; no re-identification data)' });

  const result = h('div', { 'aria-live': 'polite' });
  const selId = nextId('aud');
  const sel = h('select', { id: selId }, audiences.map((a) => h('option', { value: a.value }, a.label)));
  const btn = h('button', { type: 'button' }, 'Generate export');
  btn.addEventListener('click', busy(btn, () => runExport(ctx, sel.value, result), { doing: 'Generating export…' }));

  root.appendChild(card('Generate a data export', { id: 'sec-export' },
    h('p', null, 'The server builds the package, verifies it against its own manifest, and streams it to you as a zip. No copy is kept on the server. Each export is recorded in the audit trail.'),
    h('div', { class: 'field' }, h('label', { for: selId }, 'Package'), sel),
    h('div', { class: 'actions' }, btn),
    result));

  const histBox = h('div');
  root.appendChild(card('Exports generated in this session', { id: 'sec-history' }, histBox));
  renderHistory(histBox);

  root.appendChild(card('Evidence reports', { id: 'sec-reports',
    intro: 'The portal has no report-generation API. Reports are generated by the Python report generator (neurometric.reports.evidence) on a trusted workstation:' },
  h('pre', { class: 'json' }, h('code', null,
    '# synthetic demo reports (all seven types)\nneurometric report demo ./reports\n\n# from Python, over a StudyData bundle built from an export:\nfrom neurometric.reports.evidence import build_report\nbuild_report(study_data, "sponsor_study_summary", "./reports")')),
  table([{ key: 'id', label: 'Report type id', render: (r) => h('code', null, r.id) }, { key: 'name', label: 'Report' }],
    REPORT_TYPES.map(([id, name]) => ({ id, name })), { caption: 'Report types (PDF + JSON, each with provenance and 95% CIs)' }),
  h('p', { class: 'muted small' }, 'Every report states that it is not a regulatory submission and carries the synthetic flag when any input is synthetic.')));
}

async function runExport(ctx, audience, out) {
  clear(out).appendChild(h('p', { class: 'loading' }, 'Building and verifying the export…'));
  let res;
  try {
    res = await api(`/studies/${ctx.studyId}/exports`, { method: 'POST', raw: true, query: { audience } });
  } catch (e) {
    clear(out).appendChild(errorNotice(e, 'data exports'));
    announce('Export failed.', true);
    return;
  }
  const buf = await res.arrayBuffer();
  const disp = res.headers.get('content-disposition') || '';
  const name = (/filename="([^"]+)"/.exec(disp) || [])[1] || `neurometric-${audience}.zip`;
  const head = res.headers.get('x-neurometric-audit-head');
  const crypto = webCryptoAvailable();
  const zipSha = crypto ? await sha256Hex(buf) : null;
  let manifest = null, verifyRows = [], problem = null;
  try {
    const entries = readZip(buf);
    const me = entries.find((e) => e.name === 'manifest.json');
    if (!me) throw new Error('manifest.json missing from package');
    manifest = JSON.parse(decodeText(await me.read()));
    for (const f of manifest.files) {
      const e = entries.find((x) => x.name === f.path);
      let actual = null;
      if (e && crypto) actual = await sha256Hex(await e.read());
      verifyRows.push({ ...f, actual, ok: crypto ? actual === f.sha256 : null, present: !!e });
    }
  } catch (e) {
    problem = e.message;
  }
  const url = URL.createObjectURL(new Blob([buf], { type: 'application/zip' }));
  const allOk = verifyRows.length > 0 && verifyRows.every((r) => r.ok);
  history.unshift({ name, audience, at: new Date().toISOString(), bytes: buf.byteLength, sha256: zipSha, head, n: manifest ? manifest.n_participants : null, ok: crypto ? allOk : null, url });

  clear(out);
  out.appendChild(allOk
    ? notice('ok', h('p', null, h('span', { class: 'status status--ok' }, 'Export ready and verified'), ` — all ${verifyRows.length} files match the SHA-256 in the manifest (checked in your browser).`))
    : notice(problem ? 'bad' : 'warn', problem ? `Could not read the package: ${problem}` : (crypto ? 'Some files did not match their manifest hash.' : 'Export ready. Your browser cannot recompute SHA-256 here (needs HTTPS or localhost); hashes below are as stated by the server.')));
  out.appendChild(h('div', { class: 'tiles' },
    tile('Package', name),
    tile('Size', `${fmtNum(Math.round(buf.byteLength / 1024))} KB`),
    tile('Participants', manifest ? fmtNum(manifest.n_participants) : '—'),
    tile('Files', fmtNum(verifyRows.length))));
  out.appendChild(h('p', null, h('a', { class: 'button', href: url, download: name }, `Download ${name}`)));
  out.appendChild(h('dl', { class: 'small' },
    h('dt', null, 'Zip SHA-256 (computed in browser)'), h('dd', { class: 'hash' }, zipSha || 'not available'),
    h('dt', null, 'Audit-chain head at export'), h('dd', { class: 'hash' }, head || (manifest && manifest.audit_chain_head) || '—'),
    manifest ? [h('dt', null, 'Generated'), h('dd', null, `${fmtDateTime(manifest.generated_at)} by role ${manifest.generated_by.role}`),
      h('dt', null, 'Versions'), h('dd', null, `software ${manifest.software_version} · battery ${manifest.battery_version} · scorer ${manifest.scorer_version} · export schema ${manifest.export_schema_version}`)] : null));
  if (manifest) {
    if (manifest.banner) out.appendChild(notice('warn', manifest.banner));
    out.appendChild(table([
      { key: 'path', label: 'File', render: (r) => h('code', null, r.path) },
      { key: 'records', label: 'Records', num: true },
      { key: 'bytes', label: 'Bytes', num: true },
      { key: 'sha256', label: 'SHA-256 (manifest)', render: (r) => h('span', { class: 'hash', title: r.sha256 }, r.sha256) },
      { key: 'ok', label: 'Browser check', render: (r) => (r.ok === null ? h('span', { class: 'status status--info' }, 'not checked') : r.ok ? h('span', { class: 'status status--ok' }, 'match') : h('span', { class: 'status status--bad' }, r.present ? 'MISMATCH' : 'missing')) },
    ], verifyRows, { caption: 'Manifest: files and SHA-256 hashes' }));
    out.appendChild(h('details', null, h('summary', null, 'Disclaimers in this package'),
      h('ul', null, (manifest.disclaimers || []).map((d) => h('li', null, d)))));
  }
  announce(allOk ? `Export ready: ${verifyRows.length} files verified.` : 'Export finished with warnings.');
  const hist = document.querySelector('#sec-history');
  if (hist) renderHistory(hist.querySelector('div') || hist);
}

function renderHistory(box) {
  clear(box);
  box.appendChild(table([
    { key: 'at', label: 'Generated', render: (r) => fmtDateTime(r.at) },
    { key: 'audience', label: 'Package' },
    { key: 'n', label: 'Participants', num: true },
    { key: 'sha256', label: 'Zip SHA-256', render: (r) => h('span', { class: 'hash', title: r.sha256 || '' }, shortHash(r.sha256)) },
    { key: 'ok', label: 'Verified', render: (r) => (r.ok === null ? '—' : r.ok ? h('span', { class: 'status status--ok' }, 'yes') : h('span', { class: 'status status--bad' }, 'no')) },
    { key: 'url', label: 'File', render: (r) => h('a', { href: r.url, download: r.name }, 'Download') },
  ], history, { caption: 'Exports from this browser tab', empty: 'No exports generated yet in this session. Exports are not stored on the server.' }));
}
