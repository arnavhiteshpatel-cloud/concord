"""Data inventory: every stored table and field with purpose, data category, sensitivity,
retention and visibility. The export data dictionary is generated from the live schema joined
with this inventory, and a test asserts that every column of the schema is documented here
(so DATA_GOVERNANCE.md cannot silently drift from the code).

Sensitivity levels: ``public`` (no personal data), ``internal`` (operational, no participant
data), ``pseudonymous`` (participant-level data keyed by a random pseudonym),
``sensitive`` (pseudonymous data with elevated risk: free text, raw input streams, device
settings), ``identifying`` (re-identification key; encrypted, site-only), ``secret``
(credentials; never exported).
"""
from __future__ import annotations

from typing import Any

T = dict[str, Any]


def _t(purpose: str, category: str, sensitivity: str, retention: str, visible_to: str,
       fields: dict[str, str]) -> T:
    return {"purpose": purpose, "category": category, "sensitivity": sensitivity,
            "retention": retention, "visible_to": visible_to, "fields": fields}


