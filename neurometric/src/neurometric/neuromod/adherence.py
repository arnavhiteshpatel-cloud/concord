"""Home neuromodulation / rehabilitation evidence companion: therapy-session records and adherence.

Scope guardrails (enforced in code and tests):
* NeuroMetric records sessions; it never controls a device, never changes stimulation parameters,
  never recommends treatment. The prescribed schedule comes from the sponsor's protocol and is
  stored as given.
* Stimulation parameters are not stored as fields. If a sponsor export references device
  settings, only an opaque reference string (``device_settings_ref``) is kept.
* Adherence metrics describe recorded use; they are not dose-response claims.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from datetime import date, timedelta
from typing import Iterable, Optional

import numpy as np
import pandas as pd

NO_TREATMENT_ADVICE = ("Records and summarises device-assisted therapy sessions as reported. Does "
                       "not provide treatment instructions, control devices, modify stimulation "
                       "parameters or make clinical recommendations.")
SOURCES = ("device_export", "self_report", "care_partner_report", "clinician_entry")
FORBIDDEN_KEYS = {"amplitude", "frequency", "pulse_width", "intensity", "stim_params",
                  "current_ma", "voltage", "electrode_config", "program_settings"}


@dataclass(frozen=True)
class TherapySession:
    participant: str
    day: date
    minutes: float
    source: str
    completed: bool = True
    interruptions: int = 0
    assistance: tuple = ()  # assist types, e.g. ("setup",)
    device_label: str = ""
    device_settings_ref: str = ""  # opaque reference only

    def __post_init__(self):
        if self.source not in SOURCES:
            raise ValueError(f"source must be one of {SOURCES}")
        if self.minutes < 0 or self.minutes > 24 * 60:
            raise ValueError("minutes out of range")


@dataclass(frozen=True)
class PrescribedSchedule:
    """As specified by the sponsor protocol (stored verbatim; never generated by NeuroMetric)."""
    sessions_per_week: float
    minutes_per_session: float
    start: date
    weeks: int
    protocol_ref: str


def sessions_from_records(records: Iterable[dict]) -> list[TherapySession]:
    out = []
    for r in records:
        bad = FORBIDDEN_KEYS & {k.lower() for k in r}
        if bad:
            raise ValueError(f"refusing stimulation-parameter fields: {sorted(bad)}")
        out.append(TherapySession(**r))
    return out


def adherence(sessions: list[TherapySession], sched: PrescribedSchedule,
              prefer_source: str = "device_export") -> dict:
    """Adherence summary for ONE participant. When both device export and self-report exist for
    a day, the preferred source is used for metrics and concordance is reported."""
    df = pd.DataFrame([s.__dict__ for s in sessions])
    end = sched.start + timedelta(weeks=sched.weeks)
    if not len(df):
        return {"sessions_completed": 0, "prescribed_sessions": sched.sessions_per_week * sched.weeks,
                "session_adherence": 0.0, "note": NO_TREATMENT_ADVICE}
    df = df[(df.day >= sched.start) & (df.day < end)]
    have_pref = df[df.source == prefer_source]
    use = have_pref if len(have_pref) else df
    done = use[use.completed]
    prescribed_sessions = sched.sessions_per_week * sched.weeks
    prescribed_minutes = prescribed_sessions * sched.minutes_per_session
    weekly = done.assign(week=[(d - sched.start).days // 7 for d in done.day]).groupby("week").size()
    weekly = weekly.reindex(range(sched.weeks), fill_value=0)
    days = sorted(set(done.day))
    gaps = [(b - a).days for a, b in zip([sched.start] + days, days + [end])]
    out = {
        "source_used": prefer_source if len(have_pref) else "mixed",
        "sessions_completed": int(len(done)),
        "prescribed_sessions": prescribed_sessions,
        "session_adherence": float(min(len(done) / prescribed_sessions, 10.0)) if prescribed_sessions else np.nan,
        "minutes_completed": float(done.minutes.sum()),
        "minutes_adherence": float(done.minutes.sum() / prescribed_minutes) if prescribed_minutes else np.nan,
        "weeks_meeting_schedule": int((weekly >= sched.sessions_per_week).sum()),
        "weekly_sessions": weekly.tolist(),
        "longest_gap_days": int(max(gaps)) if gaps else None,
        "sessions_with_assistance": int(sum(bool(a) for a in done.assistance)),
        "interruptions": int(done.interruptions.sum()),
        "protocol_ref": sched.protocol_ref,
        "note": NO_TREATMENT_ADVICE,
    }
    sr = df[df.source.isin(["self_report", "care_partner_report"])]
    dv = df[df.source == "device_export"]
    if len(sr) and len(dv):
        a = set(sr[sr.completed].day)
        b = set(dv[dv.completed].day)
        out["report_vs_device_day_agreement"] = len(a & b) / len(a | b) if a | b else np.nan
        out["days_reported_not_in_device_log"] = len(a - b)
        out["days_in_device_log_not_reported"] = len(b - a)
    return out
