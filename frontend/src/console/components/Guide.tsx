// The in-app guide: what Concord is, each step of the session screen, the tools, the words used,
// and the limits of use, in plain language, so nobody needs the online documentation to start.

import { useEffect, type ReactNode } from "react";
import { SIMULATOR_TOOL, TOOL_GROUPS } from "../tools";
import { Sheet } from "./ui";

export const GUIDE_SECTIONS = [
  { id: "start", title: "What Concord is" },
  { id: "quick", title: "Try it in two minutes" },
  { id: "source", title: "Step 1 · Data source" },
  { id: "signal", title: "Step 2 · Signal check" },
  { id: "decoder", title: "Step 3 · Decoder" },
  { id: "control", title: "Step 4 · Send to apps" },
  { id: "sessions", title: "Sessions, recordings and stopping" },
  { id: "tools", title: "More tools" },
  { id: "words", title: "Words you will see" },
  { id: "safety", title: "Limits, safety and privacy" },
] as const;

export type GuideSection = (typeof GUIDE_SECTIONS)[number]["id"];

function Section({ id, title, children }: { id: GuideSection; title: string; children: ReactNode }) {
  return (
    <section className="guide-section" id={`guide-${id}`} data-testid={`guide-${id}`}>
      <h3>{title}</h3>
      {children}
    </section>
  );
}

const WORDS: [string, string][] = [
  ["Brain-computer interface (BCI)", "A system that reads brain signals and turns them into actions, such as moving a cursor."],
  ["Source", "Where the brain data comes from: the simulator, a recording file, or live equipment."],
  ["Channel", "One signal, usually from one electrode or sensor. A source can have hundreds."],
  ["Hz (samples per second)", "How many measurements each channel makes per second. 1,000 Hz is one every millisecond."],
  ["Bin", "A short slice of time (for example 20 ms) over which the signal is summarised into one number."],
  ["Features", "The summary numbers a decoder uses, for example how active each channel was in each bin."],
  ["Decoder (model)", "The part that has learned how brain activity relates to what the person intended, and turns new activity into an intended action."],
  ["Calibration (training)", "Recording a short task and fitting a decoder to it, so it learns this person and this setup."],
  ["Offline replay", "Recorded data played back from a file. It looks live, but no person is connected."],
  ["Simulated", "Made-up data generated by Concord for practice. It is not brain data."],
  ["Live stream", "Data arriving now from recording software over the network. Concord cannot verify what produced it."],
  ["LSL (Lab Streaming Layer)", "A common way for lab recording software to share data streams on a network."],
  ["Open Ephys", "Open-source recording software used in many neuroscience labs."],
  ["Plugin (add-on)", "Extra software, installed separately, that adds a new kind of source or decoder."],
  ["Intracortical, ECoG, EEG", "Electrodes inside the brain, on the surface of the brain, or on the scalp."],
  ["Provenance", "A label on every message saying where it came from (simulated, recorded, live, decoded) so it can never be mistaken for something else."],
  ["Authorize", "Allow one app to receive actions from the decoder. You can revoke it at any time."],
  ["Participant", "The person using the BCI, who looks at the participant screen."],
];

export function Guide({ section, onClose }: { section?: string; onClose: () => void }) {
  useEffect(() => {
    if (!section) return;
    // after the sheet has rendered and focused its heading
    const t = setTimeout(() => document.getElementById(`guide-${section}`)?.scrollIntoView({ block: "start" }), 0);
    return () => clearTimeout(t);
  }, [section]);
  return (
    <Sheet title="How Concord works" onClose={onClose} testId="guide" wide>
      <nav className="guide-nav" aria-label="Guide contents">
        {GUIDE_SECTIONS.map((s) => (
          <a key={s.id} href={`#guide-${s.id}`} onClick={(e) => {
            e.preventDefault();
            document.getElementById(`guide-${s.id}`)?.scrollIntoView({ block: "start" });
          }}>
            {s.title}
          </a>
        ))}
      </nav>

      <Section id="start" title="What Concord is">
        <p>
          A <b>brain-computer interface (BCI)</b> reads signals from the brain and turns them into actions, such as moving
          a cursor or choosing a word. Concord is the software in the middle. It does four things, which are the four
          steps on the main screen:
        </p>
        <ol className="guide-steps">
          <li>
            <b>Reads</b> brain signals from a recording system, a file or a simulator.
          </li>
          <li>
            <b>Checks</b> that the data is arriving complete and on time.
          </li>
          <li>
            <b>Decodes</b> the signals: a trained decoder turns brain activity into an intended action.
          </li>
          <li>
            <b>Sends</b> those actions to apps you allow, such as the communication board, and only when you turn it on.
          </li>
        </ol>
        <p>
          Concord only listens. It never sends anything to a device, so it cannot change or stimulate anything in a
          recording system.
        </p>
      </Section>

      <Section id="quick" title="Try it in two minutes (no equipment needed)">
        <ol className="guide-steps">
          <li>
            In step 1, click <b>Choose a source</b>, then <b>Connect</b> next to <b>Simulated Profile A</b>. This is
            made-up data for practice.
          </li>
          <li>
            Step 2 turns green and says <b>Good</b>: data is arriving. The moving lines are a few of the channels.
          </li>
          <li>
            In step 4, click <b>Open participant screen</b>. The communication board opens in its own window.
          </li>
          <li>
            Under <b>More tools</b>, click <b>Show</b> next to <b>Simulator controls</b>. Drag in the square pad: the
            cursor on the board moves. Click <b>Select</b> to choose the word under the cursor.
          </li>
          <li>
            When you are done, click <b>Stop everything</b> at the top of the screen.
          </li>
        </ol>
      </Section>

      <Section id="source" title="Step 1 · Data source">
        <p>Choose where the brain data comes from. You can switch at any time.</p>
        <dl className="guide-dl">
          <dt>Demo data (simulated)</dt>
          <dd>
            Made up by Concord for practice. <b>Profile A</b> has 32 channels and moves a pointer and makes selections.{" "}
            <b>Profile B</b> has 8 channels and makes selections and types letters, without a pointer. Neither is real
            brain data.
          </dd>
          <dt>Real recordings (played back)</dt>
          <dd>
            Public research recordings from people with implanted electrodes, played from files on this computer. They
            are always labelled <b>offline replay</b>: no one is connected. Concord checks every file against a
            fingerprint published with the dataset and refuses a file that was changed. The source list shows how to
            download them.
          </dd>
          <dt>Your recordings</dt>
          <dd>Anything you recorded with Concord, played back the same way.</dd>
          <dt>Live equipment</dt>
          <dd>
            If your lab&apos;s recording software streams its data over <b>LSL</b> or <b>Open Ephys</b>, Concord can
            listen to it. Concord cannot tell whether a live stream comes from real hardware or from a simulator, so it
            says <i>origin unverified</i>.
          </dd>
          <dt>Add-ons (plugins)</dt>
          <dd>
            Connectors installed separately, for example for BCI2000. They are third-party code that runs with your
            permissions: install only add-ons you trust.
          </dd>
        </dl>
        <p>
          Once connected, <b>Pause</b> stops the data for a moment, recordings can be played faster or slower, and{" "}
          <b>Disconnect</b> ends the connection.
        </p>
      </Section>

      <Section id="signal" title="Step 2 · Signal check">
        <p>Tells you whether the data is arriving complete and on time. The light means:</p>
        <dl className="guide-dl">
          <dt>Good (green)</dt>
          <dd>Data is arriving and nothing was lost in the last 10 seconds.</dd>
          <dt>Gaps detected (amber)</dt>
          <dd>Some data was lost in the last 10 seconds. Check cables, the network or the recording software.</dd>
          <dt>No signal</dt>
          <dd>Nothing has arrived for 2 seconds.</dd>
          <dt>Paused</dt>
          <dd>You paused the source.</dd>
          <dt>Interrupted, reconnecting</dt>
          <dd>The connection dropped and Concord is trying to get it back.</dd>
        </dl>
        <p>The three numbers:</p>
        <ul>
          <li>
            <b>Channels</b>: how many channels arrived in the latest data, out of how many the source said it has.
          </li>
          <li>
            <b>Data received</b>: the share of data that arrived. Only shown when the source reports its own losses;
            Concord never guesses it.
          </li>
          <li>
            <b>Delay</b>: how long data takes from reaching Concord to reaching this screen, in milliseconds.
          </li>
        </ul>
      </Section>

      <Section id="decoder" title="Step 3 · Decoder">
        <p>
          A <b>decoder</b> turns brain activity into what the person intended, for example a direction to move or a
          button to press. It has two parts:
        </p>
        <ul>
          <li>
            <b>Processing</b> cleans the raw signal and summarises it into features. Concord picks a sensible setting for
            your source; you rarely need to change it.
          </li>
          <li>
            A <b>model</b>: the part that has learned the link between features and intentions.
          </li>
        </ul>
        <p>Where a model comes from:</p>
        <ul>
          <li>
            <b>Train a decoder</b>: record a short task while the person tries the movements, then train on that
            recording. Concord shows how well the model did on a part of the recording it had not seen.
          </li>
          <li>
            <b>Model files and decoder add-ons</b> that someone else made. <b>Search for decoder add-ons</b> in the
            Start decoding panel finds installed ones. None come with Concord.
          </li>
          <li>Some recordings already contain the output of the decoder used in the study. Concord can play it back.</li>
        </ul>
        <p>
          <b>Reading the scores.</b> <i>R²</i> (for movement) goes up to 1: 1 is perfect, 0 is no better than always
          guessing the average. <i>Balanced accuracy</i> (for choices) is compared with chance. Both are measured on
          recorded data (&quot;offline&quot;), which says little about how well it would work live.
        </p>
        <p>
          You can also start decoding <b>without a model</b>. Concord then only computes the features, which is what you
          record to train one.
        </p>
      </Section>

      <Section id="control" title="Step 4 · Send to apps">
        <p>
          Decoded actions reach an app only when <b>all three</b> are true: a decoder with a model is running, you
          clicked <b>Start sending</b>, and you <b>authorized</b> that app. Otherwise nothing is sent. This step is off
          every time Concord starts.
        </p>
        <p>
          <b>Settings</b> decide how decoded output becomes actions. For a cursor: which outputs move it left/right and
          up/down, its speed, a dead-zone that ignores tiny movements, a top speed, flipping up and down, and an optional
          click. For a decoder that recognises choices: which choice does what, how sure it must be, and how long it must
          be held.
        </p>
        <p>
          <b>Stop sending</b> (the red button at the top right) stops all actions immediately. It is always there while
          sending is on.
        </p>
        <p>
          The <b>participant screen</b> is the communication board for the person using the BCI, best on a second
          screen facing them. It adapts to what is available: pointer and click, hovering to select (dwell), moving
          between items, or scanning. It has its own settings button.
        </p>
      </Section>

      <Section id="sessions" title="Sessions, recordings and stopping">
        <p>
          A <b>session</b> keeps everything from one sitting together in one folder: recordings, trained decoders, a log
          of what happened, and your notes. <b>Export</b> packs it into one file that someone else can use to check and
          re-run your results. Never type participant names or other identifying details into notes.
        </p>
        <p>
          <b>Record data</b> (in More tools) saves what the connected source sends, so you can play it back later.
        </p>
        <p>
          <b>Stop everything</b> turns sending off, closes any recording, stops decoding and disconnects the source, in
          that order.
        </p>
        <p>The session log on the right lists what happened, newest first.</p>
      </Section>

      <Section id="tools" title="More tools">
        <p>Below the four steps. Click Show on any tool to open it; you can have several open at once.</p>
        <dl className="guide-dl">
          {[...TOOL_GROUPS.flatMap((g) => g.tools), SIMULATOR_TOOL].map((t) => (
            <div key={t.id}>
              <dt>{t.title}</dt>
              <dd>
                {t.what} {t.when}
                {t.id === SIMULATOR_TOOL.id ? " Only appears while a simulated profile is connected." : ""}
              </dd>
            </div>
          ))}
        </dl>
      </Section>

      <Section id="words" title="Words you will see">
        <dl className="guide-dl">
          {WORDS.map(([w, d]) => (
            <div key={w}>
              <dt>{w}</dt>
              <dd>{d}</dd>
            </div>
          ))}
        </dl>
      </Section>

      <Section id="safety" title="Limits, safety and privacy">
        <ul>
          <li>
            <b>Research software, an early preview.</b> Not a medical device. Not for diagnosing or treating anyone, not
            for clinical use, and not for commercial use.
          </li>
          <li>
            <b>Not yet tested with real recording equipment or with a person.</b> It has been tested with simulated data
            and with recordings from public datasets. Decoder scores are from recorded data only.
          </li>
          <li>
            <b>Read-only.</b> Concord never sends anything to a recording system or an implant.
          </li>
          <li>
            <b>Using it with a person</b> requires your institution&apos;s ethics approval and your lab&apos;s own safety
            procedures.
          </li>
          <li>
            <b>Privacy.</b> Everything stays on this computer. Concord only accepts connections from this computer and
            has no user accounts or encryption, so keep it that way. <b>Saved data</b> (in More tools) shows where
            files are stored and deletes them.
          </li>
        </ul>
      </Section>
    </Sheet>
  );
}
