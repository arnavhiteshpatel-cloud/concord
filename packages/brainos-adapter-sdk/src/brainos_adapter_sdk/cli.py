README = """# {dist}

BrainOS source plugin for {display}, generated by `brainos-adapter new`.

```bash
pip install -e .            # registers the "brainos.sources" entry point "{name}"
brainos-adapter check {name} # runs it through the BrainOS plugin host and validator
pytest -q
```

Then start BrainOS (`brainos-server`) and choose **Connect a source → Plugins → {display}**.
Certify it with `brainos-certify {name}` (package `brainos-certify`).

Edit `src/{module}/plugin.py`: every `TODO` marks a place for your device's I/O and metadata.
Declare only what you know (units, modality, clock); BrainOS shows unknowns as unknown.
"""


def _new(args: argparse.Namespace) -> int:
    name: str = args.name
    if not NAME_RE.match(name):
        print(
            "name: 3-24 characters, lower-case letters, digits and '-', e.g. my-amp",
            file=sys.stderr,
        )
        return 2
    module = "brainos_" + name.replace("-", "_")
    cls = "".join(p.capitalize() for p in name.split("-")) + "Plugin"
    if keyword.iskeyword(module) or not cls.isidentifier():
        print(f"cannot derive a Python name from {name!r}", file=sys.stderr)
        return 2
    dist = f"brainos-{name}"
    display = args.display or name.replace("-", " ").title()
    root = Path(args.dir or dist)
    if root.exists() and any(root.iterdir()):
        print(f"{root} exists and is not empty", file=sys.stderr)
        return 1
    fmt = {"name": name, "module": module, "cls": cls, "dist": dist, "display": display}
    files = {
        root / "pyproject.toml": PYPROJECT.format(**fmt),
        root / "README.md": README.format(**fmt),
        root / "src" / module / "__init__.py": f'"""{display}: BrainOS source plugin."""\n',
        root / "src" / module / "plugin.py": PLUGIN.format(**fmt),
        root / "tests" / "test_plugin.py": TEST.format(**fmt),
    }
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    print(f"created {root}/ (entry point {name!r} -> {module}.plugin:{cls})")
    print(f"next: pip install -e {root} && brainos-adapter check {name}")
    return 0


def _host(extra: list[str]) -> int:
    return subprocess.call([sys.executable, "-m", "brainos_adapter_sdk.host", *extra])


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        prog="brainos-adapter", description=__doc__, formatter_class=argparse.RawTextHelpFormatter
    )
    sub = ap.add_subparsers(dest="cmd", required=True)
    n = sub.add_parser("new", help="scaffold an installable source-plugin package")
    n.add_argument("name", help="entry-point name, e.g. my-amp (becomes part of device ids)")
    n.add_argument("--dir", help="target directory (default brainos-<name>)")
    n.add_argument("--display", help="display name (default derived from the name)")
    sub.add_parser("list", help="installed plugins with their validation result")
    c = sub.add_parser("check", help="run a plugin through the host and validate it")
    c.add_argument("plugin")
    args, extra = ap.parse_known_args(argv)
    if args.cmd == "new":
        return _new(args)
    if args.cmd == "list":
        return _host(["--list", *extra])
    return _host(["--check", args.plugin, *extra])


if __name__ == "__main__":
    raise SystemExit(main())
