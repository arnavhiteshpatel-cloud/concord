"""The committed example reports are valid, consistent and never claim hardware status.

They are generated by the reference-software tests with
``HWVAL_EXAMPLES_DIR=examples/sample-reports``.
"""

from __future__ import annotations

import json
from pathlib import Path

import jsonschema
import pytest

from concord_hwval.model import Status, overall
from concord_hwval.report import SCHEMA_PATH

SAMPLES = Path(__file__).parent.parent / "examples" / "sample-reports"
EXAMPLES = sorted(SAMPLES.glob("*.hwval.json"))


@pytest.mark.parametrize("path", EXAMPLES, ids=[p.name for p in EXAMPLES])
def test_example_report(path: Path) -> None:
    rep = json.loads(path.read_text(encoding="utf-8"))
    jsonschema.validate(rep, json.loads(SCHEMA_PATH.read_text(encoding="utf-8")))
    assert rep["evidence_scope"]["hardware_verified"] is False
    assert rep["evidence_scope"]["level"] != "hardware_run_candidate"  # no hardware was used
    from concord_hwval.model import Category, Check

    checks = [
        Check(
            c["id"],
            c["title"],
            Category(c["category"]),
            c["required"],
            Status(c["status"]),
            c["summary"],
            c["method"],
        )
        for c in rep["checks"]
    ]
    assert overall(checks).value == rep["result"]
    assert (path.parent / path.name.replace(".hwval.json", ".hwval.md")).is_file()


def test_examples_present() -> None:
    names = {p.name.split(".")[0] for p in EXAMPLES}
    assert {"labrecorder-pass", "openephys-gui-pass", "openephys-gui-file-reader-loop"} <= names
