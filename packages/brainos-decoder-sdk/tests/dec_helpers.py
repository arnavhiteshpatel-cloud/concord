# host subprocesses import the test decoders through PYTHONPATH
ENV = {"PYTHONPATH": os.pathsep.join([str(DECODERS_DIR), os.environ.get("PYTHONPATH", "")])}


def ref(cls_name: str) -> str:
    return f"bos_test_decoders:{cls_name}"


WIDTH = 4
RNG = np.random.default_rng(11)


def manifest(
    model_id: str,
    family: str,
    *,
    kind: OutputKind = OutputKind.CONTINUOUS,
    dims: tuple[str, ...] = ("vx", "vy"),
) -> ModelManifest:
    probs = kind is not OutputKind.CONTINUOUS
    return ModelManifest(
        model_id=model_id,
        name=model_id,
        version="0.1.0",
        api_version=API_VERSION,
        family=family,
        description="test model generated by the test suite",
        author="tests",
        license="CC0",
        modalities=frozenset({Modality.INTRACORTICAL}),
        inputs=(
            InputSpec("features.binned", "threshold_crossing_count", 20.0, WIDTH, None, "count"),
        ),
        output=OutputSpec(
            kind,
            "class_posterior"
            if kind is OutputKind.CLASSES
            else "click_probability"
            if probs
            else "velocity",
            dims,
            "probability" if probs else "workspace/s",
            "test",
        ),
        confidence=Confidence.POSTERIOR if probs else Confidence.NONE,
        compatibility=ParticipantCompat(source_identity="lsl:test"),
    )


def run_host(path: Path, x: np.ndarray, trusted: str | None = None) -> np.ndarray:
    with SyncDecoderHost(model_path=path, trusted_sha256=trusted, env=ENV) as c:
        c.load()
        values, _ = c.step(x, None)
        # one bin at a time gives the same result (stateful models carry state)
        c.reset()
        one = np.vstack([c.step(x[i : i + 1], None)[0] for i in range(len(x))])
        assert np.array_equal(values, one)
        return values


def load_error(path: Path, trusted: str | None = None) -> DecoderHostError:
    with SyncDecoderHost(model_path=path, trusted_sha256=trusted, env=ENV) as c:
        c.manifest()
        with pytest.raises(DecoderHostError) as exc:
            c.load()
        return exc.value
