def _new(args: argparse.Namespace) -> int:
    name: str = args.name
    if not NAME_RE.match(name):
        print("name: 3-24 characters, lower-case letters, digits and '-'", file=sys.stderr)
        return 2
    module = "brainos_" + name.replace("-", "_")
    cls = "".join(p.capitalize() for p in name.split("-")) + "Decoder"
    if keyword.iskeyword(module) or not cls.isidentifier():
        print(f"cannot derive a Python name from {name!r}", file=sys.stderr)
        return 2
    dist = f"brainos-{name}"
    display = args.display or name.replace("-", " ").title()
    root = Path(args.dir or dist)
    if root.exists() and any(root.iterdir()):
        print(f"{root} exists and is not empty", file=sys.stderr)
        return 1
    fmt = {"name": name, "module": module, "cls": cls, "dist": dist, "display": display}
    files = {
        root / "pyproject.toml": PYPROJECT.format(**fmt),
        root / "README.md": README.format(**fmt),
        root / "src" / module / "__init__.py": f'"""{display}: BrainOS decoder plugin."""\n',
        root / "src" / module / "decoder.py": DECODER.format(**fmt),
        root / "tests" / "test_decoder.py": TEST.format(**fmt),
    }
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    print(f"created {root}/ (entry point {name!r} -> {module}.decoder:{cls})")
    print(f"next: pip install -e {root} && brainos-decoder check {name}")
    return 0


def _host(extra: list[str]) -> int:
    return subprocess.call([sys.executable, "-m", "brainos_decoder_sdk.host", *extra])


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        prog="brainos-decoder", description=__doc__, formatter_class=argparse.RawTextHelpFormatter
    )
    sub = ap.add_subparsers(dest="cmd", required=True)
    n = sub.add_parser("new", help="scaffold an installable decoder-plugin package")
    n.add_argument("name", help="entry-point name, e.g. my-gru")
    n.add_argument("--dir", help="target directory (default brainos-<name>)")
    n.add_argument("--display", help="display name (default derived from the name)")
    sub.add_parser("list", help="installed decoder plugins with their validation result")
    c = sub.add_parser("check", help="run a decoder (plugin or model file) through the host")
    c.add_argument("decoder", nargs="?", help="entry-point name or module:Class")
    c.add_argument("--model", help="a model manifest (<id>.manifest.json)")
    c.add_argument("--steps", default="200", help="bins to decode")
    c.add_argument("--trusted-sha256", help="for pickle/joblib/skops files you trust")
    args = ap.parse_args(argv)
    if args.cmd == "new":
        return _new(args)
    if args.cmd == "list":
        return _host(["--list"])
    extra = ["--check", "--steps", str(args.steps)]
    if args.trusted_sha256:
        extra += ["--trusted-sha256", args.trusted_sha256]
    if args.model:
        return _host(["--model", args.model, *extra])
    if not args.decoder:
        ap.error("check needs a decoder name or --model")
    return _host([args.decoder, *extra])


if __name__ == "__main__":
    raise SystemExit(main())
